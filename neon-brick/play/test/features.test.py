# 100 main stages, Golden Aim, special balls and coin continue, played through the real page.
import asyncio
from playwright.async_api import async_playwright
async def main():
    res = []
    def ok(n, c): res.append(bool(c)); print(("PASS " if c else "FAIL ") + n)
    async with async_playwright() as p:
        b = await p.chromium.launch(args=["--autoplay-policy=no-user-gesture-required"])
        pg = await b.new_page(locale="ko-KR", viewport={"width": 390, "height": 844}, device_scale_factor=2)
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto("file:///home/claude/neon-brick/index.html?release=1"); await pg.wait_for_timeout(600)
        await pg.evaluate("NBQ.Ads.tickMs = 200")
        # --- stage map: 100 main stages + 6 wide ---
        await pg.evaluate("localStorage.setItem('nbq-progress', JSON.stringify({stars:{30:2}})); location.reload()"); await pg.wait_for_timeout(700)
        await pg.click("#btnPlay"); await pg.wait_for_timeout(300)
        ok("map has 106 stage buttons and 10 chapters", await pg.locator(".grid button").count() == 106 and await pg.locator("#map h2").count() == 11)
        ok("total stars out of 318", (await pg.inner_text("#starTotal")).endswith("/ 318"))
        b31 = pg.locator("#grid5 button").first
        ok("chapter 4 starts at stage 31 and opens after stage 30", (await b31.inner_text()).startswith("31") and await b31.is_enabled())
        ok("stage 32 is still locked", await pg.locator("#grid5 button").nth(1).is_disabled())
        ok("chapter 10 ends at stage 100 (a boss)", (await pg.locator("#grid11 button").last.inner_text()).startswith("100") and "boss" in await pg.locator("#grid11 button").last.get_attribute("class"))
        await b31.click(); await pg.wait_for_timeout(300)
        ok("stage 31 HUD shows STAGE 31 · 네온 하이웨이", await pg.inner_text("#hudStage") == "STAGE 31" and await pg.inner_text("#hudChap") == "네온 하이웨이")
        await pg.evaluate("NBQ.startStage(30)"); await pg.wait_for_timeout(200); await pg.evaluate("NBQ.forceClear(2)"); await pg.wait_for_timeout(1200)
        await pg.click("#rBtns button:has-text('다음 스테이지')"); await pg.wait_for_timeout(500)
        ok("next after stage 30 is stage 31 (internal 37)", await pg.evaluate("NBQ.state.stage.n") == 37)
        await pg.evaluate("NBQ.startStage(36)"); await pg.wait_for_timeout(200); await pg.evaluate("NBQ.forceClear(2)"); await pg.wait_for_timeout(1200)
        ok("last wide special has no next button", await pg.locator("#rBtns button:has-text('다음')").count() == 0)
        await pg.evaluate("NBQ.startStage(106)"); await pg.wait_for_timeout(200); await pg.evaluate("NBQ.forceClear(2)"); await pg.wait_for_timeout(1200)
        ok("stage 100 has no next button", await pg.locator("#rBtns button:has-text('다음')").count() == 0)
        curve = await pg.evaluate("[1,10,25,37,46,56,86,106].map(n=>NBQ.Core.target(n))")
        ok(f"target clear rate falls gently {curve}", curve[0] >= .95 and all(0.55 <= x <= 0.97 for x in curve) and curve[3] > curve[-1])
        # --- Golden Aim ---
        await pg.evaluate("NBQ.startStage(5)"); await pg.wait_for_timeout(1300)
        n_plain = await pg.evaluate("NBQ.Core.aimPath(NBQ.state, 1.2).length")
        g0 = await pg.evaluate("NBQ.wallet.boosters.gold")
        await pg.click("#tray [data-b=gold]"); await pg.wait_for_timeout(200)
        ok("golden aim turns on and uses one", await pg.evaluate("NBQ.state.goldAim") and await pg.evaluate("NBQ.wallet.boosters.gold") == g0 - 1)
        ok("golden aim path has more bounces", await pg.evaluate("NBQ.Core.aimPath(NBQ.state, 1.2, 6).length") > n_plain)
        await pg.click("#tray [data-b=gold]"); await pg.wait_for_timeout(200)
        ok("second tap does not use another", await pg.evaluate("NBQ.wallet.boosters.gold") == g0 - 1)
        ok("golden button shows it is on", "on" in await pg.get_attribute("#tray [data-b=gold]", "class"))
        await pg.screenshot(path="shots/feat-gold-tray.png")
        # --- special balls ---
        await pg.evaluate("NBQ.wallet = {...NBQ.wallet, coins: 1000}; NBQ.openShop()"); await pg.wait_for_timeout(200)
        ok("shop lists 3 special balls", await pg.locator("#shopBalls .item").count() == 3)
        await pg.click("#shopBalls [data-ball=split]"); await pg.wait_for_timeout(200)
        ok("not enough coins: split ball not bought", not await pg.evaluate("NBQ.wallet.ballsOwned.split") and await pg.evaluate("NBQ.wallet.coins") == 1000)
        await pg.evaluate("NBQ.wallet = {...NBQ.wallet, coins: 5000}; NBQ.openShop()"); await pg.wait_for_timeout(200)
        await pg.click("#shopBalls [data-ball=explode]"); await pg.wait_for_timeout(200)
        ok("buying the blast ball costs 1,800 and equips it", await pg.evaluate("NBQ.wallet.ballsOwned.explode && NBQ.wallet.ball === 'explode' && NBQ.wallet.coins === 3200"))
        await pg.screenshot(path="shots/feat-shop-balls.png")
        await pg.evaluate("NBQ.startStage(8)"); await pg.wait_for_timeout(300)
        ok("equipped ball goes into the stage", await pg.evaluate("NBQ.state.ballType") == "explode")
        await pg.evaluate("window.__sp=0; const s=NBQ.state; NBQ.Core.startShot(s, 1.3); for(let i=0;i<4000&&s.status==='shooting';i++){ NBQ.Core.step(s); __sp+=s.events.filter(e=>e.type==='special').length; s.events.length=0; }")
        ok("blast ball fires its effect in a real shot", await pg.evaluate("__sp") >= 1)
        await pg.evaluate("NBQ.openShop()"); await pg.wait_for_timeout(150); await pg.click("#shopBalls [data-ball=explode]"); await pg.wait_for_timeout(150)
        ok("tapping again unequips it", await pg.evaluate("NBQ.wallet.ball") is None)
        await pg.evaluate("NBQ.wallet = {...NBQ.wallet, ball: 'explode'}; NBQ.Daily.play()"); await pg.wait_for_timeout(300)
        ok("daily challenge plays without the special ball", await pg.evaluate("NBQ.state.ballType") is None)
        # --- continue with coins ---
        await pg.evaluate("NBQ.wallet = {...NBQ.wallet, coins: 300}; NBQ.startStage(6)"); await pg.wait_for_timeout(200)
        await pg.evaluate("NBQ.forceFail()"); await pg.wait_for_timeout(1300)
        ok("fail screen offers ad and coin continue", await pg.locator("#rBtns button:has-text('이어하기 (광고)')").count() == 1 and await pg.locator("#btnCoinCont").count() == 1)
        await pg.screenshot(path="shots/feat-coin-continue.png")
        await pg.click("#btnCoinCont"); await pg.wait_for_timeout(300)
        ok("coin continue costs 250 and resumes", await pg.evaluate("NBQ.wallet.coins") == 50 and await pg.evaluate("NBQ.screen") == "play" and await pg.evaluate("NBQ.state.continued"))
        await pg.evaluate("NBQ.startStage(7)"); await pg.wait_for_timeout(200); await pg.evaluate("NBQ.forceFail()"); await pg.wait_for_timeout(1300)
        await pg.click("#btnCoinCont"); await pg.wait_for_timeout(300)
        ok("not enough coins keeps the fail screen", await pg.evaluate("NBQ.screen") == "result" and await pg.evaluate("NBQ.wallet.coins") == 50)
        await pg.evaluate("NBQ.Daily.play()"); await pg.wait_for_timeout(200); await pg.evaluate("NBQ.forceFail()"); await pg.wait_for_timeout(1300)
        ok("daily challenge has no coin continue", await pg.locator("#btnCoinCont").count() == 0)
        # old wallets get the new booster slot
        await pg.evaluate("localStorage.setItem('nbq-wallet', JSON.stringify({coins: 99, boosters: {hammer: 1, laser: 0, balls: 0, push: 0}})); location.reload()"); await pg.wait_for_timeout(600)
        ok("old saved wallet gets gold: 0 and no special ball", await pg.evaluate("NBQ.wallet.boosters.gold === 0 && NBQ.wallet.coins === 99 && !NBQ.wallet.ball"))
        ok("no JS errors", not errs)
        if errs: print(errs[:3])
        await b.close()
    print(f"\n{sum(res)} passed, {len(res) - sum(res)} failed")
asyncio.run(main())
