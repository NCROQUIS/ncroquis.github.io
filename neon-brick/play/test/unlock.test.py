# Test-only "unlock all stages" button on the map.
import asyncio
from playwright.async_api import async_playwright
async def main():
    res = []
    def ok(n, c): res.append(bool(c)); print(("PASS " if c else "FAIL ") + n)
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(locale="ko-KR", viewport={"width": 390, "height": 844}, device_scale_factor=2)
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto("file:///home/claude/neon-brick/index.html"); await pg.wait_for_timeout(500)
        await pg.click("#btnPlay"); await pg.wait_for_timeout(200)
        ok("only stage 1 open before", await pg.locator(".grid button:not([disabled])").count() == 1)
        stars0, coins0 = await pg.inner_text("#starTotal"), await pg.evaluate("NBQ.wallet.coins")
        await pg.click("#btnUnlockAll"); await pg.wait_for_timeout(200)
        ok("button opens all 106 stages", await pg.locator(".grid button:not([disabled])").count() == 106)
        ok("no stars or coins granted", await pg.inner_text("#starTotal") == stars0 and await pg.evaluate("NBQ.wallet.coins") == coins0)
        ok("button shows it is on", "켜짐" in await pg.inner_text("#btnUnlockAll"))
        await pg.screenshot(path="shots/96-unlock-all.png", full_page=True)
        await pg.click(".grid button >> text=18"); await pg.wait_for_timeout(500)
        ok("a late stage starts directly", await pg.evaluate("NBQ.screen") == "play" and await pg.evaluate("NBQ.state.stage.n") == 18)
        await pg.click("#btnBack"); await pg.wait_for_timeout(300)
        await pg.reload(); await pg.wait_for_timeout(400); await pg.evaluate("NBQ.openMap()"); await pg.wait_for_timeout(200)
        ok("setting survives reload", await pg.locator(".grid button:not([disabled])").count() == 106)
        await pg.click("#btnUnlockAll"); await pg.wait_for_timeout(200)
        ok("pressing again restores normal locks", await pg.locator(".grid button:not([disabled])").count() == 1)
        # ---- progress reset ----
        await pg.evaluate("NBQ.startStage(1)"); await pg.wait_for_timeout(100); await pg.evaluate("NBQ.forceClear(3)"); await pg.wait_for_timeout(200)
        await pg.evaluate("NBQ.startStage(2)"); await pg.wait_for_timeout(100); await pg.evaluate("NBQ.forceClear(2)"); await pg.wait_for_timeout(200)
        await pg.evaluate("NBQ.wallet.coins = 999; NBQ.Dz.st.owned.push('spin'); NBQ.Dz.save(); localStorage.setItem('nbq-daily', JSON.stringify({days:{'2026-10-31':{best:5,attempts:1,at:1}},streak:{last:'2026-10-31',n:1}}))")
        await pg.evaluate("NBQ.openMap()"); await pg.wait_for_timeout(200)
        ok("progress exists before reset", await pg.inner_text("#starTotal") == "★ 5 / 318" and await pg.locator(".grid button:not([disabled])").count() == 3)
        await pg.click("#btnReset"); await pg.wait_for_timeout(200)
        ok("reset asks for confirmation", await pg.is_visible("#sheet") and "진행 초기화" in await pg.inner_text("#sheet"))
        await pg.screenshot(path="shots/97-reset-sheet.png")
        await pg.click("#sheetBtns button:has-text('취소')"); await pg.wait_for_timeout(200)
        ok("cancel keeps everything", await pg.inner_text("#starTotal") == "★ 5 / 318")
        await pg.click("#btnReset"); await pg.wait_for_timeout(150); await pg.click("#sheetBtns button:has-text('별만')"); await pg.wait_for_timeout(250)
        ok("'stars only' clears stars and locks", await pg.inner_text("#starTotal") == "★ 0 / 318" and await pg.locator(".grid button:not([disabled])").count() == 1)
        ok("'stars only' keeps coins and dances", await pg.evaluate("NBQ.wallet.coins") == 999 and await pg.evaluate("NBQ.Dz.st.owned.includes('spin')"))
        await pg.click("#btnUnlockAll"); await pg.wait_for_timeout(150)
        await pg.click("#btnReset"); await pg.wait_for_timeout(150); await pg.click("#sheetBtns button:has-text('전부')"); await pg.wait_for_timeout(250)
        ok("'all' resets coins, boosters, dances and daily record", await pg.evaluate("NBQ.wallet.coins") == 300 and await pg.evaluate("NBQ.wallet.boosters.hammer") == 2 and await pg.evaluate("NBQ.Dz.st.owned.length") == 3 and await pg.evaluate("localStorage.getItem('nbq-daily')") is None)
        ok("reset also turns test unlock off", await pg.locator(".grid button:not([disabled])").count() == 1 and "켜짐" not in await pg.inner_text("#btnUnlockAll"))
        await pg.evaluate("NBQ.music = null"); await pg.reload(); await pg.wait_for_timeout(400)
        ok("reset survives reload and settings are kept", await pg.evaluate("NBQ.wallet.coins") == 300 and await pg.evaluate("NBQ.Dz.st.owned.length") == 3)
        ok("no JS errors", not errs)
        await b.close()
    print(f"\n{sum(res)} passed, {len(res) - sum(res)} failed")
asyncio.run(main())
