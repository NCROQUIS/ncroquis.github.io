import { NcqLang } from '../ncq/lang.js';
import { TEXTS, LANGUAGES } from './texts.mjs';
import { THROW_TEXTS } from './throw-texts.mjs';
import { MOVE_TEXTS } from './move-texts.mjs';
import { QUIT_TEXTS } from './quit-texts.mjs';
import { TEAM_TEXTS } from './team-texts.mjs';
import { ONLINE_TEXTS } from './online-texts.mjs';
import { ECONOMY_TEXTS } from './economy-texts.mjs';
for (const language of LANGUAGES) Object.assign(TEXTS[language], THROW_TEXTS[language], MOVE_TEXTS[language], QUIT_TEXTS[language], TEAM_TEXTS[language], ONLINE_TEXTS[language], ECONOMY_TEXTS[language]);
NcqLang.init({ id: 'matjjang-yut', texts: TEXTS });
export const t = (key, params) => NcqLang.t(key, params);
export { NcqLang, LANGUAGES };
